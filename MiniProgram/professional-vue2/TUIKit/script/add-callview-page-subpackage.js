/**
 * Script: add-callview-page-subpackage.js
 *
 * Subpackage version of add-callview-page.js.
 * Copies CallKit UI components and state files from the npm package
 * `@trtc/calls-uikit-wx-uniapp` into the TUIKit directory, then registers
 * the CallView page under `subPackages` in pages.json.
 *
 * This enables CallKit integration via TUIBridge for the professional
 * (full-featured) TUIKit in WeChat Mini Program (MP-WEIXIN) environment,
 * with subpackage optimization enabled.
 */

const {
  readFileSync,
  writeFileSync,
  cpSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  statSync,
} = require('fs');
const { resolve, dirname } = require('path');

const ROOT = resolve(__dirname, '..', '..');
const SRC = resolve(ROOT, 'node_modules/@trtc/calls-uikit-wx-uniapp/TUICallKit');
const DEST = resolve(ROOT, 'TUIKit');

// Source items to copy from the engine package.
const COPY_ITEMS = [
  { src: 'assets/call', dest: 'assets/call' },
  { src: 'assets/base', dest: 'assets/base' },
  { src: 'components/CallView', dest: 'components/CallView' },
  { src: 'components/GroupCallView', dest: 'components/GroupCallView' },
  { src: 'states/TUICallService', dest: 'states/TUICallService' },
  { src: 'states/CallListState.ts', dest: 'states/CallListState.ts' },
  { src: 'states/CallParticipantState.ts', dest: 'states/CallParticipantState.ts' },
  { src: 'states/DeviceState.ts', dest: 'states/DeviceState.ts' },
  { src: 'states/UIConfigState.ts', dest: 'states/UIConfigState.ts' },
  { src: 'adapter/vue-version.ts', dest: 'adapter/vue-version.ts' },
  { src: 'adapter/vue-demi.ts', dest: 'adapter/vue-demi.ts' },
  { src: 'plugin/ring', dest: 'plugin/ring' },
  { src: 'utils/permission.ts', dest: 'utils/permission.ts' },
  { src: 'constants/call.ts', dest: 'constants/call.ts' },
  { src: 'constants/chat.ts', dest: 'constants/chat.ts' },
  { src: 'call/index.ts', dest: 'call/index.ts' },
];

// --- Copy logic ---------------------------------------------------------

function copyOne({ src, dest }) {
  const srcPath = resolve(SRC, src);
  const destPath = resolve(DEST, dest);

  if (!existsSync(srcPath)) {
    console.warn(`Skip (not found): ${srcPath}`);
    return;
  }

  mkdirSync(dirname(destPath), { recursive: true });

  const stat = statSync(srcPath);
  if (stat.isDirectory()) {
    cpSync(srcPath, destPath, { recursive: true, force: true });
  } else {
    copyFileSync(srcPath, destPath);
  }
  console.log(`Copied: ${dest}`);
}

function copyFromEngine() {
  if (!existsSync(SRC)) {
    console.error(`Source directory not found: ${SRC}`);
    console.error('Please run `npm install` first to install @trtc/calls-uikit-wx-uniapp.');
    process.exit(1);
  }
  for (const item of COPY_ITEMS) copyOne(item);
}

// Append call-related exports to the existing index.ts
function appendCallExports() {
  const indexPath = resolve(DEST, 'index.ts');
  if (!existsSync(indexPath)) {
    console.warn('Skip: index.ts not found in TUIKit.');
    return;
  }

  const content = readFileSync(indexPath, 'utf-8');

  // Check if call exports are already present
  if (content.includes('useCallListState')) {
    console.log('Skipped: Call exports already present in index.ts');
    return;
  }

  const callExports = `
// --- CallKit exports (auto-generated by add-callview-page-subpackage.js) ---
export { useCallListState } from './states/CallListState';
export { useCallParticipantState } from './states/CallParticipantState';
export { useDeviceState } from './states/DeviceState';
export { useUIConfigState, FeatureButton, LayoutMode } from './states/UIConfigState';
export { TUIStore as TUICallStore, StoreName as CallStoreName, TUICallKitAPI, NAME, CallStatus, CallRole, t, uiDesign } from './states/TUICallService/index';
export { DeviceStatus } from './constants/call';
export { formatDuration, removeC2C, isJSON, JSONToObject } from './utils/index';
export { checkMicrophonePermission, checkCameraPermission, handlePermissionDenied } from './utils/permission';
export { vueVersion } from './adapter/vue-version';
`;

  writeFileSync(indexPath, content + callExports, 'utf-8');
  console.log('Done: Call exports appended to index.ts');
}

// --- Subpackage pages.json configuration ---------------------------------

const SUBPACKAGE_PAGES = [
  {
    path: 'components/CallView/CallView',
    style: {
      navigationBarTitleText: 'uni-app',
    },
  },
];

// Set `optimization.subPackages: true` in manifest.json for mp-weixin.
function enableSubpackageOptimization() {
  const file = resolve(ROOT, 'manifest.json');
  if (!existsSync(file)) {
    console.warn('Skip: manifest.json not found.');
    return;
  }

  let raw = readFileSync(file, 'utf-8');
  let manifest;
  try {
    manifest = JSON.parse(raw);
  } catch {
    console.error('Error: manifest.json is not valid JSON.');
    return;
  }

  if (!manifest['mp-weixin']) {
    manifest['mp-weixin'] = {};
  }
  if (!manifest['mp-weixin'].optimization) {
    manifest['mp-weixin'].optimization = {};
  }
  if (manifest['mp-weixin'].optimization.subPackages === true) {
    console.log('Skipped: optimization.subPackages is already enabled in manifest.json');
    return;
  }

  manifest['mp-weixin'].optimization.subPackages = true;
  writeFileSync(file, JSON.stringify(manifest, null, '  ') + '\n', 'utf-8');
  console.log('Done: optimization.subPackages set to true in manifest.json');
}

// Register TUIKit pages under subPackages in pages.json.
function registerSubpackagePages() {
  const file = resolve(ROOT, 'pages.json');
  const data = JSON.parse(readFileSync(file, 'utf-8'));

  // Ensure subPackages array exists.
  if (!data.subPackages) {
    data.subPackages = [];
  }

  // Find or create the TUIKit subpackage entry.
  let tuiSub = data.subPackages.find(s => s.root === 'TUIKit');
  if (!tuiSub) {
    tuiSub = { root: 'TUIKit', pages: [] };
    data.subPackages.push(tuiSub);
  }

  // Merge any new pages that aren't already registered.
  const existingPaths = new Set(tuiSub.pages.map(p => p.path));
  for (const pageDef of SUBPACKAGE_PAGES) {
    if (!existingPaths.has(pageDef.path)) {
      tuiSub.pages.push(pageDef);
      console.log(`Added subpackage page: TUIKit/${pageDef.path}`);
    }
  }

  // Remove CallView from main pages if it exists there
  const callViewPath = 'TUIKit/components/CallView/CallView';
  data.pages = data.pages.filter(p => p.path !== callViewPath);

  writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf-8');
  console.log('Done: TUIKit CallView page moved to subPackages in pages.json');
}

// --- Main ----------------------------------------------------------------

copyFromEngine();
appendCallExports();
enableSubpackageOptimization();
registerSubpackagePages();
console.log('All tasks finished (subpackage mode).');
